import type { Metadata } from "next";
import {
  Cinzel,
  IBM_Plex_Mono,
  IM_Fell_English,
  Share_Tech_Mono,
  UnifrakturCook,
} from "next/font/google";
import { Nav } from "@/components/ui/nav";
import { Spotlight } from "@/components/ui/hud-effects";
import { readIndex, readMeta } from "@/lib/data";
import "./globals.css";

// Plex Mono for data, Cinzel for Roman inscriptions, IM Fell for printed-marginalia italics,
// Share Tech Mono for HUD readouts, UnifrakturCook for the illuminated wordmark.
const plex = IBM_Plex_Mono({
  variable: "--nf-plex",
  subsets: ["latin"],
  weight: ["400", "500", "600"],
});
const cinzel = Cinzel({
  variable: "--nf-cinzel",
  subsets: ["latin"],
  weight: ["400", "600", "700"],
});
const fell = IM_Fell_English({
  variable: "--nf-fell",
  subsets: ["latin"],
  weight: "400",
  style: ["normal", "italic"],
});
const hud = Share_Tech_Mono({
  variable: "--nf-hud",
  subsets: ["latin"],
  weight: "400",
});
const fraktur = UnifrakturCook({
  variable: "--nf-fraktur",
  subsets: ["latin"],
  weight: "700",
});

export const metadata: Metadata = {
  title: "cali — codex futurum",
  description:
    "Monitor the cali scout: runs, startups, people and connections.",
};

// Runs before first paint so the saved theme never flashes. Default is dark (lapis night + gilt).
const THEME_SCRIPT = `try{var d=document.documentElement,t=localStorage.getItem("cali-theme");
if(t==="light")d.classList.remove("dark");
if(localStorage.getItem("cali-crt")==="off")d.setAttribute("data-crt","off");
if(sessionStorage.getItem("cali-booted"))d.setAttribute("data-booted","");else sessionStorage.setItem("cali-booted","1")}catch(e){}`;

const BOOT = [
  "> INVOCATIO … CODEX FUTURUM",
  "> lapis · aurum · cinnabaris",
  "> cor machinae …………… [ OK ]",
  "> oculus apertus ………… [ OK ]",
  "> SCRUTATOR PARATUS",
];

export default function RootLayout({ children }: LayoutProps<"/">) {
  const runs = readIndex();
  const last = runs.at(-1) ?? null;
  const demo = readMeta()?.demo === true;

  return (
    <html
      lang="en"
      className={`${plex.variable} ${cinzel.variable} ${fell.variable} ${hud.variable} ${fraktur.variable} dark h-full antialiased`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
      </head>
      <body className="flex min-h-full flex-col font-mono text-sm text-zinc-900 dark:text-emerald-300">
        <div aria-hidden className="boot">
          <pre className="ascii font-hud text-sm leading-7 tracking-wider">
            {BOOT.map((line, i) => (
              <span
                key={line}
                className="boot-line"
                style={{ "--i": i } as React.CSSProperties}
              >
                {line}
              </span>
            ))}
          </pre>
        </div>
        <Spotlight />
        <Nav lastRunPassed={last ? last.passed : null} />
        {demo && (
          <div className="border-b border-amber-500/60 bg-amber-200 px-4 py-1 text-center font-hud text-xs uppercase tracking-[0.18em] text-zinc-900 dark:bg-amber-950 dark:text-amber-300">
            Demo data — fictional companies and runs, generated by
            backend/scripts/make_demo_data.py
          </div>
        )}
        <div className="mx-auto w-full max-w-6xl flex-1 px-4 py-8">
          {children}
        </div>
        <footer className="px-4 pb-5 pt-2 text-center">
          <div aria-hidden className="rule mx-auto mb-3 max-w-md" />
          <p className="font-fell text-sm italic text-zinc-600 dark:text-emerald-500/80">
            cali · static build · data from backend/data
            <span className="mx-2 not-italic opacity-60">·</span>
            <span className="font-hud text-[11px] not-italic uppercase tracking-[0.25em]">
              ars longa, vita brevis
            </span>
          </p>
        </footer>
      </body>
    </html>
  );
}
