import type { Metadata } from "next";
import { Geist_Mono, Instrument_Serif } from "next/font/google";
import { Nav } from "@/components/ui/nav";
import { readDataHealth, readIndex, readMeta } from "@/lib/data";
import { latestRun, runState } from "@/lib/metrics";
import "./globals.css";

// Geist Mono for data and labels, Instrument Serif for headings and numerals.
const mono = Geist_Mono({
  variable: "--nf-mono",
  subsets: ["latin"],
});
const serif = Instrument_Serif({
  variable: "--nf-serif",
  subsets: ["latin"],
  weight: "400",
  style: ["normal", "italic"],
});

export const metadata: Metadata = {
  title: "cali — connection & builder dashboard",
  description:
    "Monitor the cali scout: runs, startups, people and connections.",
};

// Runs before first paint so the saved theme never flashes. Default is light (paper).
const THEME_SCRIPT = `try{var d=document.documentElement,t=localStorage.getItem("cali-theme");
if(t==="dark")d.classList.add("dark");else d.classList.remove("dark")}catch(e){}`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  const runs = readIndex();
  const last = latestRun(runs); // greatest run_id, not the last array slot
  const demo = readMeta()?.demo === true;
  const health = readDataHealth();

  return (
    <html
      lang="en"
      className={`${mono.variable} ${serif.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
      </head>
      <body className="flex min-h-full flex-col font-mono text-[13px] text-zinc-900 dark:text-zinc-200">
        <a
          href="#main"
          className="sr-only focus:not-sr-only focus:absolute focus:left-2 focus:top-2 focus:z-50 focus:bg-white focus:px-2 focus:py-1 dark:focus:bg-black"
        >
          Skip to content
        </a>
        <Nav lastRun={last ? runState(last) : null} />
        {health.length > 0 && (
          <div
            role="alert"
            className="border-b border-rose-600 bg-rose-100 px-4 py-1 text-center text-xs text-zinc-900 dark:bg-rose-950 dark:text-rose-200"
          >
            Data file{health.length > 1 ? "s" : ""} could not be read:{" "}
            {health.map((h) => `${h.file} (${h.error.slice(0, 80)})`).join("; ")}
            . The pages below may be empty until it is fixed.
          </div>
        )}
        {demo && (
          <div className="border-b border-amber-500/40 bg-amber-100 px-4 py-1 text-center text-xs text-zinc-900 dark:bg-amber-950 dark:text-amber-300">
            Demo data — fictional companies and runs, generated by
            backend/scripts/make_demo_data.py
          </div>
        )}
        <main id="main" className="mx-auto w-full max-w-6xl flex-1 px-4 py-6 sm:py-10">
          {children}
        </main>
        <footer className="mx-auto w-full max-w-6xl px-4 pb-6">
          <p className="border-t border-zinc-900/15 pt-3 text-xs text-zinc-600 dark:border-zinc-100/15 dark:text-zinc-400">
            <span className="serif text-base italic">cali</span> · static build
            · data from {demo ? "frontend/demo-data (fictional)" : "backend/data"}{" "}
            · press <kbd className="border border-zinc-900/25 px-1 dark:border-zinc-100/25">?</kbd> on
            the queue or startups for keyboard shortcuts
          </p>
        </footer>
      </body>
    </html>
  );
}
