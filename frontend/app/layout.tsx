import type { Metadata } from "next";
import { IBM_Plex_Mono, VT323 } from "next/font/google";
import { Nav } from "@/components/ui/nav";
import { readIndex, readMeta } from "@/lib/data";
import "./globals.css";

const plex = IBM_Plex_Mono({
  variable: "--font-plex",
  subsets: ["latin"],
  weight: ["400", "500", "600"],
});
const vt323 = VT323({
  variable: "--font-vt323",
  subsets: ["latin"],
  weight: "400",
});

export const metadata: Metadata = {
  title: "cali — connection & builder dashboard",
  description:
    "Monitor the cali scout: runs, startups, people and connections.",
};

// Runs before first paint so the saved theme never flashes. Default is dark (green phosphor).
const THEME_SCRIPT = `try{var d=document.documentElement,t=localStorage.getItem("cali-theme");
if(t==="light")d.classList.remove("dark");
if(localStorage.getItem("cali-crt")==="off")d.setAttribute("data-crt","off")}catch(e){}`;

export default function RootLayout({ children }: LayoutProps<"/">) {
  const runs = readIndex();
  const last = runs.at(-1) ?? null;
  const demo = readMeta()?.demo === true;

  return (
    <html
      lang="en"
      className={`${plex.variable} ${vt323.variable} dark h-full antialiased`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
      </head>
      <body className="flex min-h-full flex-col bg-white font-mono text-sm text-zinc-900 dark:bg-black dark:text-emerald-300">
        <Nav lastRunPassed={last ? last.passed : null} />
        {demo && (
          <div className="border-b-2 border-zinc-900 bg-amber-200 px-4 py-1 text-center text-xs font-medium text-zinc-900 dark:border-amber-400/60 dark:bg-amber-950 dark:text-amber-300">
            DEMO DATA — fictional companies and runs, generated by
            backend/scripts/make_demo_data.py
          </div>
        )}
        <div className="mx-auto w-full max-w-6xl flex-1 px-4 py-8">
          {children}
        </div>
        <footer className="border-t-2 border-zinc-900 px-4 py-3 text-center text-xs text-zinc-500 dark:border-emerald-500/40 dark:text-emerald-500/70">
          cali · static build · data from backend/data
        </footer>
      </body>
    </html>
  );
}
